import { z } from "zod";

const DEFAULT_CLIENT_ENV = {
  NEXT_PUBLIC_FIREBASE_API_KEY: "mock-api-key-for-local-dev",
  NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN: "synapta-dev.firebaseapp.com",
  NEXT_PUBLIC_FIREBASE_PROJECT_ID: "synapta-dev",
  NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET: "synapta-dev.appspot.com",
  NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID: "123456789012",
  NEXT_PUBLIC_FIREBASE_APP_ID: "1:123456789012:web:abcdef1234567890",
};

const DEFAULT_SERVER_ENV = {
  ...DEFAULT_CLIENT_ENV,
  FIREBASE_ADMIN_PROJECT_ID: "synapta-dev",
  FIREBASE_ADMIN_CLIENT_EMAIL: "firebase-adminsdk@synapta-dev.iam.gserviceaccount.com",
  FIREBASE_ADMIN_PRIVATE_KEY: "-----BEGIN PRIVATE KEY-----\nMIIEvgIBADANBgkqhkiG9w0BAQEFAASCBKgwggSkAgEAAoIBAQC3\n-----END PRIVATE KEY-----\n",
  GEMINI_API_KEY: "mock-gemini-key",
  GEMINI_MODEL: "gemini-2.5-flash",
  ADMIN_EMAILS: "admin@synapta.edu",
  STUDENT_TOKEN_LIMIT: 50000,
  TEACHER_TOKEN_LIMIT: 200000,
};

const clientEnvSchema = z.object({
  NEXT_PUBLIC_FIREBASE_API_KEY: z.string().default(DEFAULT_CLIENT_ENV.NEXT_PUBLIC_FIREBASE_API_KEY),
  NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN: z.string().default(DEFAULT_CLIENT_ENV.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN),
  NEXT_PUBLIC_FIREBASE_PROJECT_ID: z.string().default(DEFAULT_CLIENT_ENV.NEXT_PUBLIC_FIREBASE_PROJECT_ID),
  NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET: z.string().default(DEFAULT_CLIENT_ENV.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET),
  NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID: z.string().default(DEFAULT_CLIENT_ENV.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID),
  NEXT_PUBLIC_FIREBASE_APP_ID: z.string().default(DEFAULT_CLIENT_ENV.NEXT_PUBLIC_FIREBASE_APP_ID),
});

const serverEnvSchema = clientEnvSchema.extend({
  FIREBASE_ADMIN_PROJECT_ID: z.string().default(DEFAULT_SERVER_ENV.FIREBASE_ADMIN_PROJECT_ID),
  FIREBASE_ADMIN_CLIENT_EMAIL: z.string().default(DEFAULT_SERVER_ENV.FIREBASE_ADMIN_CLIENT_EMAIL),
  FIREBASE_ADMIN_PRIVATE_KEY: z.string().default(DEFAULT_SERVER_ENV.FIREBASE_ADMIN_PRIVATE_KEY),
  GEMINI_API_KEY: z.string().default(DEFAULT_SERVER_ENV.GEMINI_API_KEY),
  GEMINI_MODEL: z.string().default(DEFAULT_SERVER_ENV.GEMINI_MODEL),
  ADMIN_EMAILS: z.string().default(DEFAULT_SERVER_ENV.ADMIN_EMAILS),
  STUDENT_TOKEN_LIMIT: z.coerce.number().default(DEFAULT_SERVER_ENV.STUDENT_TOKEN_LIMIT),
  TEACHER_TOKEN_LIMIT: z.coerce.number().default(DEFAULT_SERVER_ENV.TEACHER_TOKEN_LIMIT),
});

export type ClientEnv = z.infer<typeof clientEnvSchema>;
export type ServerEnv = z.infer<typeof serverEnvSchema>;

let cachedServerEnv: ServerEnv | null = null;
let cachedClientEnv: ClientEnv | null = null;

export function getClientEnv(): ClientEnv {
  if (cachedClientEnv) return cachedClientEnv;

  const raw = {
    NEXT_PUBLIC_FIREBASE_API_KEY: process.env.NEXT_PUBLIC_FIREBASE_API_KEY || DEFAULT_CLIENT_ENV.NEXT_PUBLIC_FIREBASE_API_KEY,
    NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN || DEFAULT_CLIENT_ENV.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN,
    NEXT_PUBLIC_FIREBASE_PROJECT_ID: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || DEFAULT_CLIENT_ENV.NEXT_PUBLIC_FIREBASE_PROJECT_ID,
    NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET || DEFAULT_CLIENT_ENV.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET,
    NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || DEFAULT_CLIENT_ENV.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID,
    NEXT_PUBLIC_FIREBASE_APP_ID: process.env.NEXT_PUBLIC_FIREBASE_APP_ID || DEFAULT_CLIENT_ENV.NEXT_PUBLIC_FIREBASE_APP_ID,
  };

  const result = clientEnvSchema.safeParse(raw);
  if (!result.success) {
    console.warn("⚠️ Client environment variable parsing warning, using defaults:", result.error.format());
    cachedClientEnv = DEFAULT_CLIENT_ENV;
    return cachedClientEnv;
  }

  cachedClientEnv = result.data;
  return cachedClientEnv;
}

export function getServerEnv(): ServerEnv {
  if (typeof window !== "undefined") {
    throw new Error("getServerEnv cannot be called on the client side.");
  }

  if (cachedServerEnv) return cachedServerEnv;

  const raw = {
    NEXT_PUBLIC_FIREBASE_API_KEY: process.env.NEXT_PUBLIC_FIREBASE_API_KEY || DEFAULT_SERVER_ENV.NEXT_PUBLIC_FIREBASE_API_KEY,
    NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN || DEFAULT_SERVER_ENV.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN,
    NEXT_PUBLIC_FIREBASE_PROJECT_ID: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || DEFAULT_SERVER_ENV.NEXT_PUBLIC_FIREBASE_PROJECT_ID,
    NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET || DEFAULT_SERVER_ENV.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET,
    NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || DEFAULT_SERVER_ENV.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID,
    NEXT_PUBLIC_FIREBASE_APP_ID: process.env.NEXT_PUBLIC_FIREBASE_APP_ID || DEFAULT_SERVER_ENV.NEXT_PUBLIC_FIREBASE_APP_ID,
    FIREBASE_ADMIN_PROJECT_ID: process.env.FIREBASE_ADMIN_PROJECT_ID || DEFAULT_SERVER_ENV.FIREBASE_ADMIN_PROJECT_ID,
    FIREBASE_ADMIN_CLIENT_EMAIL: process.env.FIREBASE_ADMIN_CLIENT_EMAIL || DEFAULT_SERVER_ENV.FIREBASE_ADMIN_CLIENT_EMAIL,
    FIREBASE_ADMIN_PRIVATE_KEY: process.env.FIREBASE_ADMIN_PRIVATE_KEY || DEFAULT_SERVER_ENV.FIREBASE_ADMIN_PRIVATE_KEY,
    GEMINI_API_KEY: process.env.GEMINI_API_KEY || DEFAULT_SERVER_ENV.GEMINI_API_KEY,
    GEMINI_MODEL: process.env.GEMINI_MODEL || DEFAULT_SERVER_ENV.GEMINI_MODEL,
    ADMIN_EMAILS: process.env.ADMIN_EMAILS || DEFAULT_SERVER_ENV.ADMIN_EMAILS,
    STUDENT_TOKEN_LIMIT: process.env.STUDENT_TOKEN_LIMIT || DEFAULT_SERVER_ENV.STUDENT_TOKEN_LIMIT,
    TEACHER_TOKEN_LIMIT: process.env.TEACHER_TOKEN_LIMIT || DEFAULT_SERVER_ENV.TEACHER_TOKEN_LIMIT,
  };

  const result = serverEnvSchema.safeParse(raw);
  if (!result.success) {
    console.warn("⚠️ Server environment variable parsing warning, using defaults:", result.error.format());
    cachedServerEnv = DEFAULT_SERVER_ENV;
    return cachedServerEnv;
  }

  cachedServerEnv = result.data;
  return cachedServerEnv;
}
